function Rplus_FrozenRank()
	script.run_in_callback(function()
		stats.set_int("MPX_CHAR_SET_RP_GIFT_ADMIN", 1)
		FindNewSession()
		script.yield(200)
		while true do
			if HUD.IS_WARNING_MESSAGE_READY_FOR_CONTROL() then
				script.yield(300);PAD.SET_CONTROL_VALUE_NEXT_FRAME(2, 201, 1)
			end
			if CAMERA.IS_GAMEPLAY_CAM_RENDERING() and stats.get_int("MPX_CHAR_XP_FM") ~= -2147483648 then
                local scaleform = GRAPHICS.REQUEST_SCALEFORM_MOVIE("MP_BIG_MESSAGE_FREEMODE")
                script.yield(2000)
				stats.set_int("MPX_CHAR_XP_FM", -2147483648);STATS.STAT_SAVE(0, 0, 3, 0)
                if GRAPHICS.HAS_SCALEFORM_MOVIE_LOADED(scaleform) then
				    GRAPHICS.BEGIN_SCALEFORM_MOVIE_METHOD(scaleform, "SHOW_MISSION_PASSED_MESSAGE")
				    GRAPHICS.SCALEFORM_MOVIE_METHOD_ADD_PARAM_PLAYER_NAME_STRING("~r~Congorats!")
				    GRAPHICS.SCALEFORM_MOVIE_METHOD_ADD_PARAM_PLAYER_NAME_STRING("You are now a certified ~y~~EX_R*~~r~~h~ N00B!")
				    GRAPHICS.END_SCALEFORM_MOVIE_METHOD()
				    notify.info("TinkerScript - Frozen Rank", "Frozen Rank: Congorats! You are now a certified n00b!")
				    for i = 1, 60*9 do
				    	GRAPHICS.DRAW_SCALEFORM_MOVIE_FULLSCREEN(scaleform, 255, 255, 255, 255, 0)
				    	script.yield(0)
				    end return
                end
			end
			script.yield(0)
		end
	end)
end

